CREATE TABLE lots (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       TEXT        NOT NULL UNIQUE,
    kind       TEXT        NOT NULL CHECK (kind IN ('raw', 'intermediate', 'serial')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Kenar: output_lot_id, input_lot_id kullanılarak üretildi.
CREATE TABLE lot_inputs (
    output_lot_id BIGINT NOT NULL REFERENCES lots (id),
    input_lot_id  BIGINT NOT NULL REFERENCES lots (id),
    quantity      BIGINT NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (output_lot_id, input_lot_id),
    CHECK (output_lot_id <> input_lot_id)
);

-- Birincil anahtar geri izlemeyi (output -> input) kapsar; bu dizin ileri izleme içindir.
CREATE INDEX lot_inputs_input_idx ON lot_inputs (input_lot_id, output_lot_id);

CREATE TABLE shipments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       TEXT        NOT NULL UNIQUE,
    customer   TEXT        NOT NULL,
    shipped_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE shipment_items (
    shipment_id BIGINT NOT NULL REFERENCES shipments (id),
    lot_id      BIGINT NOT NULL REFERENCES lots (id),
    PRIMARY KEY (shipment_id, lot_id)
);

CREATE INDEX shipment_items_lot_idx ON shipment_items (lot_id);

